// Writes the server copy of the nickname filter from src/nick.js, so both always use the same lists:
//   node tools/nick-sql.mjs > supabase/migrations/<stamp>_own_nick.sql
import { NICK_BAD_CYR, NICK_BAD_LAT, NICK_RESERVED, NICK_LEN } from '../src/nick.js';
const arr = a => `array[${a.map(w => `'${w}'`).join(', ')}]`;
console.log(String.raw`-- Own nicknames (text) next to the word ones, checked here exactly like src/nick.js checkNick (generated by tools/nick-sql.mjs).
create or replace function public.bb_nick_form(s text, lat boolean) returns text language sql immutable as $$
  select regexp_replace(regexp_replace(
    translate(translate(lower(s), 'әғқңөұүһіёй', 'агкноуухиеи'),
      case when lat then 'авекмнорстух013457@$' else 'abcehkmnoprtuxy3046@' end,
      case when lat then 'abekmhopctyxoieastas' else 'абсенкмпоргтихузочба' end),
    '[^a-zа-я]', '', 'g'), '(.)\1+', '\1', 'g');
$$;

create or replace function public.bb_nick_ok(t text) returns boolean language plpgsql immutable as $$
declare s text := btrim(regexp_replace(coalesce(t, ''), '\s+', ' ', 'g')); cyr text; lat text; plain text; w text;
begin
  if s <> coalesce(t, '') or char_length(s) < ${NICK_LEN[0]} or char_length(s) > ${NICK_LEN[1]} then return false; end if;
  if s !~ '^[A-Za-zА-Яа-яЁёӘәҒғҚқҢңӨөҰұҮүҺһІі0-9 _.\-]+$' then return false; end if;
  if regexp_replace(s, '[ _.\-]', '', 'g') ~ '[0-9]{5,}' or s ~* '\.(kz|com|ru|net|org|me|io)\M' then return false; end if;
  cyr := bb_nick_form(s, false); lat := bb_nick_form(s, true); plain := regexp_replace(lower(s), '[ _.\-]', '', 'g');
  foreach w in array ${arr(NICK_RESERVED)} loop if position(w in plain) > 0 or position(w in lat) > 0 then return false; end if; end loop;
  foreach w in array ${arr(NICK_BAD_CYR)} loop if position(w in cyr) > 0 then return false; end if; end loop;
  foreach w in array ${arr(NICK_BAD_LAT)} loop if position(w in lat) > 0 then return false; end if; end loop;
  return true;
end $$;

create or replace function public.bb_valid_nick(n jsonb) returns boolean language sql immutable as $$
  select case when jsonb_typeof(n -> 't') = 'string' then (select count(*) from jsonb_object_keys(n)) = 1 and public.bb_nick_ok(n ->> 't')
    else coalesce(jsonb_typeof(n -> 'a') = 'number' and jsonb_typeof(n -> 'n') = 'number' and jsonb_typeof(n -> 'd') = 'number'
      and (n ->> 'a') ~ '^\d+$' and (n ->> 'n') ~ '^\d+$' and (n ->> 'd') ~ '^\d+$'
      and (n ->> 'a')::int between 0 and 19 and (n ->> 'n')::int between 0 and 19 and (n ->> 'd')::int between 10 and 999, false) end
$$;

-- friends are found by either kind of nickname
create or replace function public.find_players(p_nick jsonb) returns jsonb language plpgsql security definer set search_path = public as $$
declare me uuid := bb_me();
begin
  if me is null then raise exception 'no profile'; end if;
  return coalesce((select jsonb_agg(bb_card(p, me) order by p.last_seen desc) from (
    select * from profiles p
    where p.id <> me and p.last_seen > now() - interval '60 days'
      and case when jsonb_typeof(p_nick -> 't') = 'string' then lower(p.nick ->> 't') = lower(p_nick ->> 't')
        else (p.nick ->> 'a') = (p_nick ->> 'a') and (p.nick ->> 'n') = (p_nick ->> 'n') and (p.nick ->> 'd') = (p_nick ->> 'd') end
    order by p.last_seen desc limit 10) p), '[]'::jsonb);
end $$;
revoke execute on function public.bb_nick_form(text, boolean), public.bb_nick_ok(text) from public, anon, authenticated;`);
